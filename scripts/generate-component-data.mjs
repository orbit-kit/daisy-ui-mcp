import { promises as fs } from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const componentsDir = path.join(rootDir, "daisyui-mcp", "components");
const outputFile = path.join(rootDir, "src", "data", "components.generated.ts");
const docsBaseUrl = "https://daisyui.com/components";

const INCLUDE_EXAMPLES = process.env.DAISYUI_INCLUDE_EXAMPLES !== "false";
const MAX_EXAMPLES_PER_COMPONENT =
  Number.parseInt(process.env.DAISYUI_MAX_EXAMPLES_PER_COMPONENT ?? "", 10) || 8;
const MAX_EXAMPLE_LENGTH =
  Number.parseInt(process.env.DAISYUI_MAX_EXAMPLE_LENGTH ?? "", 10) || 4000;
const FETCH_TIMEOUT_MS = Number.parseInt(process.env.DAISYUI_FETCH_TIMEOUT_MS ?? "", 10) || 15000;
const FETCH_CONCURRENCY = Number.parseInt(process.env.DAISYUI_FETCH_CONCURRENCY ?? "", 10) || 4;

const namedEntities = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
};

const getDescription = (markdown) => {
  const lines = markdown.split(/\r?\n/);
  const headerIndex = lines.findIndex((line) => line.startsWith("### "));

  if (headerIndex === -1) {
    return "";
  }

  for (let index = headerIndex + 1; index < lines.length; index += 1) {
    const value = lines[index].trim();

    if (value.length > 0) {
      return value;
    }
  }

  return "";
};

const buildOutput = (records) => {
  const serialized = JSON.stringify(records, null, 2);

  return `/**
 * This file is auto-generated by scripts/generate-component-data.mjs
 * Do not edit manually.
 */

export type ComponentDoc = {
  description: string
  markdown: string
}

export const COMPONENT_DOCS: Record<string, ComponentDoc> = ${serialized}
`;
};

const decodeHtmlEntities = (value) => {
  return value
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(Number.parseInt(hex, 16)))
    .replace(/&#([0-9]+);/g, (_, decimal) => String.fromCodePoint(Number.parseInt(decimal, 10)))
    .replace(/&([a-zA-Z]+);/g, (match, name) => namedEntities[name] ?? match);
};

const clampExample = (value) => {
  if (value.length <= MAX_EXAMPLE_LENGTH) {
    return value;
  }

  return `${value.slice(0, MAX_EXAMPLE_LENGTH).trimEnd()}\n...`;
};

const extractCodeBlocksFromPage = (pageHtml) => {
  const pattern = /<pre[^>]*class=(['"])[^'"]*shiki[^'"]*\1[^>]*>\s*<code>([\s\S]*?)<\/code>\s*<\/pre>/g;
  const seen = new Set();
  const uniqueCodeBlocks = [];

  for (const match of pageHtml.matchAll(pattern)) {
    const codeContent = match[2] ?? "";

    const normalized = decodeHtmlEntities(
      codeContent
        .replace(/<\/span>\s*<span class=(['"])line\1>/g, "\n")
        .replace(/<span class=(['"])line\1>/g, "")
        .replace(/<br\s*\/?>/g, "\n")
        .replace(/<[^>]+>/g, ""),
    )
      .replace(/\$\$/g, "")
      .replace(/\r\n/g, "\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim();

    if (normalized.length === 0) {
      continue;
    }

    const dedupeKey = normalized.replace(/\s+/g, " ").trim();
    if (seen.has(dedupeKey)) {
      continue;
    }

    seen.add(dedupeKey);
    uniqueCodeBlocks.push(clampExample(normalized));
  }

  return uniqueCodeBlocks;
};

const fetchWithTimeout = async (url) => {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);

  try {
    const response = await fetch(url, {
      headers: {
        "User-Agent": "daisyui-docs-api-generator/1.0",
      },
      signal: controller.signal,
    });

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }

    return await response.text();
  } finally {
    clearTimeout(timeout);
  }
};

const getExamplesForComponent = async (componentName) => {
  if (!INCLUDE_EXAMPLES || MAX_EXAMPLES_PER_COMPONENT <= 0) {
    return [];
  }

  const pageUrl = `${docsBaseUrl}/${componentName}/`;

  try {
    const html = await fetchWithTimeout(pageUrl);
    const examples = extractCodeBlocksFromPage(html);
    return examples.slice(0, MAX_EXAMPLES_PER_COMPONENT);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`Skipping examples for ${componentName}: ${message}`);
    return [];
  }
};

const appendExamplesToMarkdown = (markdown, componentName, examples) => {
  if (examples.length === 0) {
    return markdown;
  }

  const docsUrl = `${docsBaseUrl}/${componentName}/`;
  const lines = [markdown.trimEnd(), "", "#### Examples"];

  examples.forEach((example, index) => {
    lines.push(
      "",
      `##### Example ${index + 1}`,
      "```html",
      example,
      "```",
    );
  });

  lines.push("", `[More examples on daisyUI docs](${docsUrl})`, "");

  return lines.join("\n");
};

const mapWithConcurrency = async (items, concurrency, mapper) => {
  const results = new Array(items.length);
  const workerCount = Math.max(1, Math.min(concurrency, items.length));
  let index = 0;

  const workers = Array.from({ length: workerCount }, async () => {
    while (true) {
      const currentIndex = index;
      index += 1;

      if (currentIndex >= items.length) {
        return;
      }

      results[currentIndex] = await mapper(items[currentIndex], currentIndex);
    }
  });

  await Promise.all(workers);
  return results;
};

const main = async () => {
  const files = (await fs.readdir(componentsDir))
    .filter((file) => file.endsWith(".md"))
    .sort((left, right) => left.localeCompare(right));

  if (files.length === 0) {
    throw new Error(`No markdown files found in ${componentsDir}`);
  }

  const records = {};

  const componentData = await mapWithConcurrency(
    files,
    FETCH_CONCURRENCY,
    async (fileName) => {
      const componentName = fileName.slice(0, -3);
      const fullPath = path.join(componentsDir, fileName);
      const baseMarkdown = (await fs.readFile(fullPath, "utf8")).replace(/\r\n/g, "\n");
      const examples = await getExamplesForComponent(componentName);
      const markdown = appendExamplesToMarkdown(baseMarkdown, componentName, examples);

      return {
        componentName,
        description: getDescription(baseMarkdown),
        markdown,
        exampleCount: examples.length,
      };
    },
  );

  let totalExamples = 0;

  for (const component of componentData) {
    totalExamples += component.exampleCount;

    records[component.componentName] = {
      description: component.description,
      markdown: component.markdown,
    };
  }

  await fs.mkdir(path.dirname(outputFile), { recursive: true });
  await fs.writeFile(outputFile, buildOutput(records), "utf8");

  console.log(
    `Generated ${files.length} components (${totalExamples} examples) in ${outputFile}`,
  );
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
